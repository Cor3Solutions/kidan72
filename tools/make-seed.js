/* =========================================================
   KIDAN 72 — Builds database/seed.sql from js/data.js
   (the starting content for the database).

   Only needed again if you rebuild the database from scratch
   after changing js/data.js. Run from the website folder:
       node tools/make-seed.js
   ========================================================= */

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.join(__dirname, "..");
const src = fs.readFileSync(path.join(root, "js", "data.js"), "utf8");
const ctx = {};
vm.runInNewContext(src + "\nthis.KIDAN = KIDAN;", ctx);
const K = ctx.KIDAN;

const q = v => {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return String(v);
  return "'" + String(v)
    .replace(/\\/g, "\\\\").replace(/'/g, "''")
    .replace(/\n/g, "\\n").replace(/\r/g, "\\r") + "'";
};
const json = v => (v === undefined ? "NULL" : q(JSON.stringify(v)));
const out = [];
const row = (table, obj) =>
  out.push(`INSERT INTO ${table} (${Object.keys(obj).join(", ")}) VALUES (${Object.values(obj).join(", ")});`);

out.push("-- =========================================================");
out.push("--  KIDAN 72 — Starting content, copied from js/data.js");
out.push("--  Generated by tools/make-seed.js on " + new Date().toISOString().slice(0, 10));
out.push("--  admin/setup.php loads this automatically.");
out.push("-- =========================================================");
out.push("SET NAMES utf8mb4;");
out.push("");

out.push("-- Contact details and brand film");
const c = K.contact || {};
[["contact_messenger", c.messenger], ["contact_facebook", c.facebook], ["contact_viber", c.viber],
 ["contact_email", c.email], ["brand_film", K.brandFilm]]
  .forEach(([k, v]) => row("settings", { k: q(k), v: q(v || "") }));
out.push("");

out.push("-- Categories");
Object.entries(K.categories).forEach(([code, name], i) => row("categories", { code: q(code), name: q(name), sort: (i + 1) * 10 }));
out.push("");

const notSold = K.notSoldSeparately || [];
const price = s => (typeof K.prices[s] === "number" ? K.prices[s] : null);

out.push("-- Bags");
K.bags.forEach((b, i) => row("products", {
  serial: q(b.serial), kind: q("bag"), cat: "NULL", icon: q(b.icon || ""), name: q(b.name), label: q(b.label || ""),
  short_text: q(b.short || ""), summary: q(b.summary || ""), why: q(""), steps: "NULL", spec: q(""), maintain: q(""),
  parts: "NULL", specs: json(b.specs), search_q: q(b.q || ""), video: q(b.video || ""), price: q(price(b.serial)),
  photos: Number(b.photos) || 1, photo_hidden: b.photo === false ? 1 : 0,
  sold_separately: notSold.includes(b.serial) ? 0 : 1, sort: (i + 1) * 10
}));
out.push("");

out.push("-- Items");
K.items.forEach((it, i) => row("products", {
  serial: q(it.serial), kind: q("item"), cat: q(it.cat), icon: q(it.icon || ""), name: q(it.name), label: q(""),
  short_text: q(it.short || ""), summary: q(""), why: q(it.why || ""), steps: json(it.steps), spec: q(it.spec || ""),
  maintain: q(it.maintain || ""), parts: json(it.parts), specs: "NULL", search_q: q(it.q || ""), video: q(it.video || ""),
  price: q(price(it.serial)), photos: Number(it.photos) || 1, photo_hidden: it.photo === false ? 1 : 0,
  sold_separately: notSold.includes(it.serial) ? 0 : 1, sort: (i + 1) * 10
}));
out.push("");

out.push("-- What is inside each bag");
K.bags.forEach(b => [...(b.includes || []), ...(b.contents || [])].forEach((s, i) =>
  row("bag_contents", { bag_serial: q(b.serial), child_serial: q(s), sort: (i + 1) * 10 })));
out.push("");

out.push("-- Training modules");
K.modules.forEach((m, i) => row("modules", {
  code: q(m.code), icon: q(m.icon || ""), name: q(m.name), short_text: q(m.short || ""), lessons: json(m.lessons || []),
  search_q: q(m.q || ""), video: q(m.video || ""), sort: (i + 1) * 10
}));
K.modules.forEach(m => (m.items || []).forEach((s, i) =>
  row("module_items", { module_code: q(m.code), serial: q(s), sort: (i + 1) * 10 })));
out.push("");

out.push("-- Readiness Check");
K.readiness.forEach((r, i) => row("readiness", { code: q(r.code), text: q(r.text), module_code: q(r.module || null), sort: (i + 1) * 10 }));
out.push("");

out.push("-- Kit page slideshow");
(K.kitSlides || []).forEach((s, i) => row("kit_slides", { src: q(s.src), fallback: q(s.fallback || ""), caption: q(s.caption || ""), sort: (i + 1) * 10 }));
out.push("");

fs.writeFileSync(path.join(root, "database", "seed.sql"), out.join("\n") + "\n");
console.log("database/seed.sql written:",
  K.bags.length, "bags,", K.items.length, "items,", K.modules.length, "modules,", K.readiness.length, "readiness questions");
